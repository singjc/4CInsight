import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=file=>readFileSync(new URL(file,import.meta.url),'utf8')
test('single main run action and separate overview and detailed views',()=>{
 const main=read('../main.js')
 assert.match(main,/id="integrative-run-complete"/)
 assert.match(main,/Run complete analysis/)
 assert.match(main,/id="integrative-view-overview"/)
 assert.match(main,/id="integrative-view-details"/)
 assert.match(main,/integrativeOverviewPanel\(\)/)
 assert.match(main,/integrativeDetailsPanel\(\)/)
 assert.match(main,/i1AlignmentPanel\(\)/)
 assert.match(main,/sourceBiologicalPanel\(\)/)
})
test('required steps are verified and source processing stays local',()=>{
 const main=read('../main.js')
 assert.match(main,/await i1RunAlignment\(\)/)
 assert.match(main,/await i2bRunDirect\(\)/)
 assert.match(main,/await i2RunFusion\(\)/)
 assert.match(main,/await runJointStructure\(\)/)
 assert.match(main,/await runJointStability\(\)/)
 assert.match(main,/await runBiologicalFeatureRanking\(\)/)
 assert.match(main,/if\(!state\.i2StructureResult\)throw/)
 assert.match(main,/if\(!state\.i2Result\)throw/)
 assert.match(main,/controller\.signal/)
 assert.doesNotMatch(read('../integrative-workflow.js'),/\bfetch\s*\(|XMLHttpRequest|WebSocket|\/api\//)
})
test('view only moves validated science outputs; does not use clinical labels for fitting',()=>{
 const main=read('../main.js')
 assert.match(main,/integrativeSummaryHtml\(/)
 assert.match(main,/integrativeInfluenceHtml\(/)
 assert.match(main,/modalityOverviewHtml\(report\)/)
 assert.match(main,/featureLollipopHtml\(state\.bioFeatureResult/)
 assert.match(main,/Feature rankings are post-fit associations/)
 assert.match(main,/No p-values, FDR, pathway claims or clinical subgroup labels are inferred/)
 assert.match(main,/role="tabpanel"/)
 assert.match(main,/id="integrative-stop-run"/)
 assert.match(main,/id="integrative-live-source-bar"/)
 assert.match(main,/integrative-live-source-status/)
})
test('navigation keeps old workflow components under details, not the overview',()=>{
 const main=read('../main.js')
 const part=main.slice(main.indexOf('function integrativeOverviewPanel() {'),main.indexOf('function integrativeDetailsPanel() {'))
 assert.doesNotMatch(part,/\$\{i1AlignmentPanel\(\)\}|\$\{i2DistancePanel\(\)\}|\$\{jointStabilityPanel\(\)\}/)
 const details=main.slice(main.indexOf('function integrativeDetailsPanel() {'),main.indexOf('async function runCompleteIntegrativeAnalysis() {'))
 for(const name of ['i1AlignmentPanel','i2DistancePanel','jointStructurePanel','jointStabilityPanel','biologicalFindingsPanel'])assert.match(details,new RegExp(`\\$\\{${name}\\(\\)\\}`))
})
